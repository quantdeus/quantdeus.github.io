#!/usr/bin/env node
// Reproducible zero-external-input ITC baseline: not an attempt to impersonate extraterrestrial communication.
import { mkdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { generatePCM, pcmToWav, ENGINE_VERSION } from './signal.mjs';

const RUN_ID = 'ITC-QD-V1-20261015-001';
const QUESTION = 'Содержит ли цифровой сигнал воспроизводимую информацию о QuantDeus?';
const exportDir = path.resolve(process.env.ITC_SESSION_OUTPUT || 'artifacts/itc-session-v1');
const definition = [
  { blindId: 'A', role: 'experimental', seed: 'QUANTDEUS-ITC-20261015-A' },
  { blindId: 'B', role: 'control', seed: 'QUANTDEUS-ITC-20261015-B' }
];

function summarize(pcm) {
  let sum=0,peak=0, crossings=0;
  for(let i=0; i<pcm.length; i++){
    const x=pcm[i]; sum += x*x; peak=Math.max(peak,Math.abs(x));
    if(i && ((pcm[i]>=0)!==(pcm[i-1]>=0))) crossings++;
  }
  return {peak:Number(peak.toFixed(6)),rms:Number(Math.sqrt(sum/pcm.length).toFixed(6)),
    zeroCrossingRate:Number((crossings/pcm.length).toFixed(6))};
}
function runSession() {
  mkdirSync(exportDir,{recursive:true});
  const generated = definition.map(entry=>{
    const {pcm,config}=generatePCM({seed:entry.seed,mode:'brown',
      logicalChannels:256,durationSec:10,gain:0.20});
    const wav = Buffer.from(pcmToWav(pcm,config.sampleRate));
    const wavSha256=createHash('sha256').update(wav).digest('hex');
    const name=RUN_ID+'-'+entry.blindId+'.wav';
    writeFileSync(path.join(exportDir,name),wav);
    return {blindId:entry.blindId,file:name,source:'synthetic',
      syntheticMethod:'seeded pseudo-random brown noise',
      parameters:config,wavSha256,metrics:summarize(pcm)};
  });
  const manifest={schemaVersion:'itc-session-v1',runId:RUN_ID,experimentQuestion:QUESTION,
    generatedBy:'QuantDeus standalone deterministic software',
    engineVersion:ENGINE_VERSION,modelInterpretations:'not included in primary capture',
    receiverHardware:false,microphoneCapture:false,externalInputCaptured:false,
    contactEstablished:false,claimedExternalMessages:[],
    privateDataTransferred:false,
    blindedBeforeAnalysis:generated.map(({blindId,file,wavSha256,metrics})=>({blindId,file,wavSha256,metrics})),
    sourcesRevealedOnCompletion:generated.map(({blindId,role,seed})=>({blindId,role,seed})),
    interpretationRule:'No voices or semantic messages may be attributed to entities without independently verifiable external source and controlled validation.'};
  writeFileSync(path.join(exportDir,RUN_ID+'.json'),JSON.stringify(manifest,null,2)+'\n');
  const [a,b] = generated;
  const lines=[
    '# QuantDeus ITC Station V1 — Session '+RUN_ID,'',
    '> Digital baseline trial only. Both recordings are synthetic signals from known code; this session has no external receive channel.','',
    '## Research question',QUESTION,'',
    '## Procedures',
    '- Captured 2 × 10-second synthesized brown-noise WAV tracks (mono 44.1 kHz).',
    '- A and B were generated with independent deterministic seeds at same level and duration.',
    '- Experimental/control assignments are revealed in the JSON after generation.',
    '- Not a true blind participant test: no independent human annotators have yet evaluated these recordings.',
    '- No microphone, radio, network source or communication input was connected.','',
    '| Channel | RMS | Peak | Zero crossing fraction | SHA-256 |',
    '| --- | ---: | ---: | ---: | --- |',
    ...generated.map(g=> '| '+g.blindId+' | '+g.metrics.rms+' | '+g.metrics.peak+' | '+g.metrics.zeroCrossingRate+' | \`'+g.wavSha256+'\` |'),
    '', '## Result',
    'Status: **baseline captured, no external input and no verified contact**.',
    'No message was received or decoded. Noise patterns are not evidence of external intelligence.','',
    '## Next verification',
    'Obtain opt-in microphone/receiver audio in a separate capture, compare against matched controls, preregister blind scoring and require independent replication.',
    '', '## Traceability', 'Generated by \`node experiments/itc-v1/session.mjs\`.',
    'Audio and JSON exist only in the workflow artifact / local output; not committed to the public repository.',
    ''
  ];
  writeFileSync(path.join(exportDir,RUN_ID+'-report.md'),lines.join('\n'));
  process.stdout.write(JSON.stringify({ok:true,runId:RUN_ID,
    output:exportDir,tracks:generated.map(x=>({id:x.blindId,sha256:x.wavSha256,metrics:x.metrics})),
    externalInputCaptured:false,contactEstablished:false},null,2)+'\n');
  return manifest;
}
if(process.argv[1] && path.resolve(process.argv[1])===path.resolve(new URL(import.meta.url).pathname))runSession();
export { runSession, summarize, RUN_ID, QUESTION };
